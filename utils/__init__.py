from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict


def write_report(config: Dict[str, Any], capture_path: str) -> str:
    report_cfg = config.get("report", {})
    report_path = Path(report_cfg.get("output_file", "./sessions/report.md"))
    report_path.parent.mkdir(parents=True, exist_ok=True)

    title = report_cfg.get("title", "Auren Recon report")
    target = config.get("authorized_target", {})
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        f"# {title}",
        "",
        f"- Generated: {generated_at}",
        f"- Target: {target.get('identifier', 'unknown')}",
        f"- Owner: {target.get('owner', 'unknown')}",
        f"- Capture: {capture_path}",
        "",
        "## Summary",
        "",
        "This report was generated by Auren Recon in a documented, authorized workflow.",
        "",
        "## Notes",
        "",
        "- This repository provides orchestration and safety checks for external tools.",
        "- Actual Bluetooth analysis requires separately-installed tooling and explicit authorization.",
    ]

    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(report_path)
